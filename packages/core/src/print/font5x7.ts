/** two rows above the letter (acute, dot) or below it (ogonek) */
const ACUTE = [0x02, 0x04], DOT = [0, 0x04], OGONEK = [0x02, 0x01];
/** Polish capitals: base letter and mark */
const MARKED: Record<string, [string, number[], 'above' | 'below']> = {
  'Ą': ['A', OGONEK, 'below'], 'Ę': ['E', OGONEK, 'below'], // i18n-ok: glyph data
  'Ć': ['C', ACUTE, 'above'], 'Ń': ['N', ACUTE, 'above'], 'Ó': ['O', ACUTE, 'above'], 'Ś': ['S', ACUTE, 'above'], 'Ź': ['Z', ACUTE, 'above'], // i18n-ok: glyph data
  'Ż': ['Z', DOT, 'above'], // i18n-ok: glyph data
};

/** the glyph of a character as 11 rows (2 above the letter, 7 letter rows, 2 below) of 5 bits */
export function glyph(ch: string): number[] {
  const c = ch.toUpperCase(), m = MARKED[c];
  if (m) { const g = G[m[0]]; return m[2] === 'above' ? [...m[1], ...g, 0, 0] : [0, 0, ...g, ...m[1]]; }
  return [0, 0, ...(G[c] ?? G['?']), 0, 0];
}

