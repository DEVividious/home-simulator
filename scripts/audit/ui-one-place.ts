// npm run audit:ui — the UI gate (ADR 0037, 0043): one action, one place, and child-level language. Runs the checks of
// scripts/audit/ui-rules.ts (the same as src/home/tests/uiRegistry.test.ts) and writes reports/ui/actions.md — every action, its
// place, test id, labels, mode and where it is mounted; the list usability reports refer to (ADR 0045). Exit 1 on any problem.
import fs from 'node:fs';
import path from 'node:path';
import { activateProject } from '../../src/project/active';
import { buildProjectIndex, readProjectDir } from '../../src/project/node';
import { setProjectIndex } from '../../src/project/registry';
import { dictionary } from '../../src/i18n';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
// thumbnails are drawn on a canvas — in Node they are empty, which React reports for every <img>; nothing to fix in the app
const warn = console.error;
console.error = (...a: unknown[]) => { if (!String(a[0]).includes('An empty string ("") was passed to the src attribute')) warn(...a); };
setProjectIndex(buildProjectIndex(ROOT));
activateProject(readProjectDir(path.join(ROOT, 'projects', 'demo-apartment')));
// the app modules read the active project when they load — imported after it is set
const R = await import('./ui-rules');
const { chromeStates } = await import('./ui-matrix');
const { ACTIONS } = await import('../../src/home/ui/registry');

const checks: [string, string[]][] = [
  ['registry', R.registryProblems()],
  ['mounted once', R.mountProblems()],
  ['no direct handlers', R.handlerProblems()],
  ['test ids in one file', R.testidProblems()],
  ['known duplicates', R.KNOWN_DUPLICATES.map((d) => `still listed: ${d}`)],
  ['language', R.languageProblems()],
  ['unused keys', R.unusedKeys()],
];
const states = chromeStates();
checks.push([`rendered chrome (${states.length} states)`, states.flatMap(R.renderProblems)]);

const en = dictionary('en'), pl = dictionary('pl'), mounts = R.mounts();
const rows = Object.entries(ACTIONS).map(([id, a]) => {
  const d = a as { label: string; place: string; testid: string; advanced?: boolean; capability?: string; module?: string; keys?: string[]; control?: boolean };
  return `| ${id} | ${d.place} | \`${d.testid}\` | ${en[d.label] ?? '?'} | ${pl[d.label] ?? '?'} | ${d.advanced ? 'advanced' : 'all'}${d.capability ? ` · ${d.capability}` : ''}${d.module ? ` · ${d.module}` : ''} | ${(d.keys ?? []).join(', ')} | ${(mounts.get(id) ?? []).join(', ')}${d.control ? ' (control)' : ''} |`;
});
const total = checks.reduce((n, [, p]) => n + p.length, 0);
const md = [
  '# UI actions — one action, one place', '',
  `Generated by \`npm run audit:ui\`. ${Object.keys(ACTIONS).length} actions; ${total ? `**${total} problem(s)**` : 'all checks passed'}.`, '',
  '| id | place | test id | English | Polish | mode | keys | mounted in |', '|---|---|---|---|---|---|---|---|', ...rows, '',
  '## Checks', '', ...checks.map(([name, p]) => `- ${name}: ${p.length ? `${p.length} problem(s)` : 'ok'}`), '',
  ...checks.filter(([, p]) => p.length).flatMap(([name, p]) => [`### ${name}`, '', ...p.slice(0, 200).map((x) => `- ${x}`), '']),
];
fs.mkdirSync(path.join(ROOT, 'reports/ui'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'reports/ui/actions.md'), md.join('\n'));
console.log(`UI audit: ${Object.keys(ACTIONS).length} actions · ${states.length} rendered states · ${total} problem(s) → reports/ui/actions.md`);
for (const [name, p] of checks) { console.log(`  ${p.length ? 'FAIL' : 'ok  '} ${name}${p.length ? ` (${p.length})` : ''}`); for (const x of p.slice(0, 20)) console.log(`       ${x}`); }
process.exit(total ? 1 : 0);
