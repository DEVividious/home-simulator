#!/usr/bin/env node
// Generates src/i18n/dictionaries.ts — static imports of every dictionary part src/i18n/<lang>/<area>.json (static imports work
// in the browser, in vitest, in the Vite config bundle and in vite-node CLIs). Run after adding or removing a part file:
//   node scripts/i18n/gen.mjs        (npm run i18n:gen; npm run audit:i18n checks it is up to date)
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const DIR = path.join(ROOT, 'src', 'i18n');
const langs = fs.readdirSync(DIR, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
const ident = (l, a) => `${l}_${a.replace(/[^a-z0-9]/gi, '_')}`;
let imports = '', body = '';
for (const l of langs) {
  const parts = fs.readdirSync(path.join(DIR, l)).filter((f) => f.endsWith('.json')).sort().map((f) => f.slice(0, -5));
  for (const a of parts) imports += `import ${ident(l, a)} from './${l}/${a}.json';\n`;
  body += `  ${l}: { ${parts.map((a) => `...${ident(l, a)}`).join(', ')} },\n`;
}
const out = `// GENERATED by scripts/i18n/gen.mjs from src/i18n/<lang>/<area>.json — do not edit by hand.\n${imports}\nexport const DICTS: Record<string, Record<string, string>> = {\n${body}};\n`;
const file = path.join(DIR, 'dictionaries.ts');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (cur !== out) { console.error('src/i18n/dictionaries.ts is out of date — run: npm run i18n:gen'); process.exit(1); }
} else fs.writeFileSync(file, out);
console.log(`i18n: ${langs.length} languages`);
